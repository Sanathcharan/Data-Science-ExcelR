# Hypertuning
def prepare_sequences_for_window(window):
    train_scaled = scaled_values[:train_end]
    validation_scaled = scaled_values[train_end-window:val_end]
    X_train_temp, y_train_temp = create_sequences(train_scaled,window)
    X_val_temp, y_val_temp = create_sequences(validation_scaled,window)
    return (X_train_temp,y_train_temp,X_val_temp,y_val_temp)

# Tune LSTM
tuning_results = []
for window in [6, 12, 18]:
    Xtr, ytr, Xv, yv = prepare_sequences_for_window(window)
    for units in [32, 64]:
        model = Sequential()
        model.add(LSTM(units,activation='tanh',input_shape=(window, 1)))
        model.add(Dropout(0.2))
        model.add(Dense(1))
        model.compile(optimizer='adam',loss='mse')
        early_stop_tuning = EarlyStopping(monitor='val_loss',patience=10,restore_best_weights=True)
        model.fit(Xtr,ytr,validation_data=(Xv, yv),epochs=80,batch_size=16,callbacks=[early_stop_tuning],verbose=0)
        val_pred_scaled = model.predict(Xv,verbose=0)
        val_actual = scaler.inverse_transform(yv.reshape(-1, 1)).ravel()
        val_pred = scaler.inverse_transform(val_pred_scaled).ravel()
        rmse = np.sqrt(mean_squared_error(val_actual,val_pred))
        tuning_results.append([window,units,rmse])

tuning_df = pd.DataFrame(tuning_results,columns=['Window Size','LSTM Units','Validation RMSE'])
