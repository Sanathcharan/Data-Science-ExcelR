# Create evalution function
def evaluate_model(model, X_test, y_test):
    predictions_scaled = model.predict(X_test,verbose=0)
    actual = scaler.inverse_transform(y_test.reshape(-1, 1)).ravel()
    predictions = scaler.inverse_transform(predictions_scaled).ravel()
    rmse = np.sqrt(mean_squared_error(actual,predictions))
    mae = mean_absolute_error(actual,predictions)
    mape = np.mean(np.abs((actual - predictions) /np.where(actual == 0, 1, actual))) * 100
    return rmse, mae, mape, actual, predictions

