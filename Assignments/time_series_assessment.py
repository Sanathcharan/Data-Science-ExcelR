## Grid search ARIMA
import itertools
d = 1
p_values = range(0, 3)
q_values = range(0, 3)
results = []
for p, q in itertools.product(p_values, q_values):
    try:
        m = ARIMA(train, order=(p, d, q)).fit()
        results.append({"p": p, "d": d, "q": q, "AIC": m.aic, "BIC": m.bic})
    except Exception:
        results.append({"p": p, "d": d, "q": q, "AIC": np.nan, "BIC": np.nan})
order_search = pd.DataFrame(results).sort_values("AIC").reset_index(drop=True)
order_search

# Select best orders
best_order = (order_search.loc[0, "p"], d, order_search.loc[0, "q"])
best_order = tuple(int(x) for x in best_order)
print(f"Selected ARIMA order (p, d, q) by lowest AIC: {best_order}")

