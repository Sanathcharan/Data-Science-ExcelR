# Erorr metrics
def evaluate(actual, predicted, label):
    mae = mean_absolute_error(actual, predicted)
    rmse = np.sqrt(mean_squared_error(actual, predicted))
    mape = np.mean(np.abs((actual - predicted) / actual)) * 100
    return {"Model": label, "MAE": mae, "RMSE": rmse, "MAPE (%)": mape}
metrics = pd.DataFrame([
    evaluate(test.values, arima_forecast.values, f"ARIMA{best_order}"),
    evaluate(test.values, ets_forecast.values, "Exponential Smoothing (Holt, damped)"),
]).set_index("Model")
metrics.round(5)

# navie baseline
naive_forecast = pd.Series(np.repeat(train.iloc[-1], H), index=test.index)
naive_metrics = evaluate(test.values, naive_forecast.values, "Naive (Random Walk) Baseline")
