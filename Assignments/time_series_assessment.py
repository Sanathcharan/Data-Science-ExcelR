## Stationary checks
def adf_report(series, label):
    result = adfuller(series.dropna(), autolag="AIC")
    print(f"\nADF Test: {label}")
    print(f"ADF statistic: {result[0]:.3f}")
    print(f"p-value:       {result[1]:.3f}")
    print(f"Used lags:     {result[2]}")
    print(f"Critical values: {result[4]}")
    if result[1] < 0.05:
        print("-> Stationary (reject H0 of unit root) at 5% level.")
    else:
        print("-> Non-stationary (fail to reject H0 of unit root) at 5% level.")
adf_report(ts, "Level series (USD_AUD)")
adf_report(ts.diff(), "First difference of USD_AUD")

