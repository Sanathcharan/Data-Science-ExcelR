def recommend_anime_adaptive(title, min_results=5, top_n=10, start_threshold=0.8, step=0.1, min_threshold=0.3):
    threshold = start_threshold
    while threshold >= min_threshold:
        recs = recommend_anime(title, top_n=top_n, threshold=threshold)
        if len(recs) >= min_results:
            print(f"Using threshold={threshold:.2f} -> {len(recs)} results")
            return recs
        threshold -= step
    print("Falling back to top_n with no threshold.")
    return recommend_anime(title, top_n=top_n)
recommend_anime_adaptive('Fullmetal Alchemist: Brotherhood')

def genre_overlap_report(title, top_n=10):
    recs = recommend_anime(title, top_n=top_n)
    target_genres = set(df.loc[indices[title], 'genre_list']) if title in indices else None
    if target_genres is None:
        print("Title not found for overlap report.")
        return recs
    overlaps = []
    for name in recs['name']:
        row = df[df['name'] == name].iloc[0]
        overlap = len(target_genres & set(row['genre_list'])) / max(len(target_genres), 1)
        overlaps.append(round(overlap, 2))
    recs['genre_overlap'] = overlaps
    return recs
genre_overlap_report('Gintama')

