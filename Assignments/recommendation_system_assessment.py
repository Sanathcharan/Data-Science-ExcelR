# Map anime name -> row index (handles exact-match lookups)
indices = pd.Series(df.index, index=df['name']).drop_duplicates()

def recommend_anime(title, top_n=10, threshold=None):
    if title not in indices:
        # Simple fuzzy fallback: case-insensitive substring match
        matches = df[df['name'].str.contains(title, case=False, na=False, regex=False)]
        if matches.empty:
            raise ValueError(f"'{title}' not found in dataset.")
        idx = matches.index[0]
        print(f"Exact match not found. Using closest match: '{df.loc[idx, 'name']}'")
    else:
        idx = indices[title]
        if isinstance(idx, pd.Series):  # duplicate names
            idx = idx.iloc[0]
    sim_scores = list(enumerate(cosine_sim[idx]))
    sim_scores = [s for s in sim_scores if s[0] != idx]  # exclude itself
    sim_scores.sort(key=lambda x: x[1], reverse=True)
    if threshold is not None:
        sim_scores = [s for s in sim_scores if s[1] >= threshold]
    sim_scores = sim_scores[:top_n]
    result_idx = [i for i, _ in sim_scores]
    scores = [s for _, s in sim_scores]
    result = df.loc[result_idx, ['name', 'genre', 'type', 'rating', 'members']].copy()
    result['similarity'] = scores
    return result.reset_index(drop=True)

